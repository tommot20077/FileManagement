package xyz.dowob.filemanagement.component.provider.providerInterface;

import reactor.core.publisher.Mono;
import xyz.dowob.filemanagement.entity.User;

/**
 * 基於反應式編程模型的令牌管理介面，提供非阻塞式令牌生成、驗證和撤銷操作。
 *
 * <p>此介面定義了系統中所有令牌提供者必須實現的核心功能，確保令牌管理操作以非阻塞方式執行。
 * 所有操作均返回 Mono 類型，支持反應式流處理模式，提供高並發環境下的優異性能表現。</p>
 *
 * <p>令牌生命週期管理包括生成具有適當過期時間的令牌、驗證令牌的有效性和完整性，
 * 以及在需要時撤銷特定使用者的所有有效令牌。實現類應確保令牌的安全性和唯一性，
 * 防止令牌偽造和重放攻擊。</p>
 *
 * <p>安全性考量：實現類必須確保令牌包含足夠的熵值以防止暴力破解，
 * 使用適當的加密算法進行簽名，並實施適當的過期機制以限制令牌的有效期。
 * 在高負載環境下，應考慮令牌驗證的性能影響和緩存策略。</p>
 *
 * @author yuan
 * @version 1.0
 * @since 1.0
 * @see xyz.dowob.filemanagement.entity.User
 * @see reactor.core.publisher.Mono
 */
public interface TokenProvider {
    /**
     * 為指定使用者生成安全令牌，包含使用者身份資訊和適當的過期時間。
     *
     * <p>此方法根據提供的使用者實體生成具有唯一標識的令牌字串。令牌應包含足夠的資訊
     * 以便後續驗證使用者身份，同時確保令牌的安全性和不可偽造性。實現類應使用適當的
     * 加密算法對令牌進行簽名，並設置合理的過期時間以平衡安全性和使用者體驗。</p>
     *
     * <p>生成的令牌格式和內容由具體實現類決定，但應確保：</p>
     * <ul>
     *   <li>令牌具有足夠的熵值以防止暴力破解</li>
     *   <li>包含使用者唯一標識資訊</li>
     *   <li>設置適當的過期時間戳</li>
     *   <li>使用安全的簽名算法防止篡改</li>
     * </ul>
     *
     * @param user 要為其生成令牌的使用者實體，不能為 null，必須包含有效的使用者標識
     * @return 包含生成令牌字串的 Mono，令牌格式由實現類定義。
     *         如果生成失敗，Mono 將發出錯誤信號
     */
    Mono<String> generateToken(User user);

    /**
     * 驗證令牌的有效性和完整性，確認令牌與指定使用者 ID 的匹配性。
     *
     * <p>此方法執行完整的令牌驗證流程，包括簽名驗證、過期時間檢查、使用者身份匹配等。
     * 驗證過程應確保令牌未被篡改、未過期且屬於指定的使用者。實現類應採用常數時間比較
     * 以防止時序攻擊，並適當處理各種驗證失敗情況。</p>
     *
     * <p>驗證流程包括以下步驟：</p>
     * <ol>
     *   <li>檢查令牌格式的有效性</li>
     *   <li>驗證令牌簽名的完整性</li>
     *   <li>檢查令牌是否已過期</li>
     *   <li>確認令牌中的使用者 ID 與提供的 userId 參數匹配</li>
     *   <li>檢查令牌是否已被撤銷（如果實現支持）</li>
     * </ol>
     *
     * <p>如果驗證成功，返回令牌中包含的使用者 ID；如果驗證失敗，
     * Mono 將發出空值或錯誤信號，具體行為由實現類定義。</p>
     *
     * @param token 要驗證的令牌字串，不能為 null 或空字串
     * @param userId 預期的使用者 ID，用於驗證令牌所有權，不能為 null
     * @return 包含驗證成功後使用者 ID 的 Mono。如果驗證失敗，返回空的 Mono 或發出錯誤信號
     */
    Mono<Long> validateToken(String token, Long userId);

    /**
     * 撤銷指定使用者的所有有效令牌，確保這些令牌立即失效無法再次使用。
     *
     * <p>此方法用於主動使特定使用者的所有令牌失效，通常在以下情況下調用：</p>
     * <ul>
     *   <li>使用者主動登出系統</li>
     *   <li>檢測到帳號安全風險需要強制登出</li>
     *   <li>管理員撤銷使用者的訪問權限</li>
     *   <li>使用者密碼被重置或更改</li>
     * </ul>
     *
     * <p>實現類應確保撤銷操作的即時性和完整性。對於基於狀態的令牌系統，
     * 應將令牌標記為已撤銷；對於無狀態的令牌系統（如 JWT），應通過黑名單機制
     * 或更新密鑰的方式使令牌失效。撤銷操作完成後，該使用者的所有後續令牌驗證
     * 請求都應失敗。</p>
     *
     * <p>此操作是冪等的，多次調用同一使用者 ID 的撤銷操作不會產生副作用。
     * 如果指定的使用者 ID 不存在或沒有有效令牌，操作仍應正常完成。</p>
     *
     * @param userId 要撤銷令牌的使用者 ID，不能為 null
     * @return 表示撤銷操作完成的空 Mono。操作完成後 Mono 發出完成信號，
     *         如果撤銷過程中發生錯誤，Mono 將發出錯誤信號
     */
    Mono<Void> revokeToken(Long userId);

}
